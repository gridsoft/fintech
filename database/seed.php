$counts = ['class' => 0, 'group' => 0, 'account' => 0];

$insert = $pdo->prepare('INSERT IGNORE INTO accounts (code, name, type, parent_id, is_active) VALUES (?, ?, ?, ?, 1)');
$findId = $pdo->prepare('SELECT id FROM accounts WHERE code = ?');

function insertAccount(PDOStatement $insert, PDOStatement $findId, string $code, string $name, string $type, ?int $parentId): int
{
    $insert->execute([$code, $name, $type, $parentId]);
    $findId->execute([$code]);
    return (int) $findId->fetchColumn();
}

foreach ($plan as $classCode => $class) {
    $classId = insertAccount($insert, $findId, $classCode, $class['name'], $class['type'] ?? 'asset', null);
    $counts['class']++;

    foreach ($class['groups'] as $groupCode => $group) {
        $groupType = $group['type'] ?? $class['type'] ?? 'asset';
        $groupId = insertAccount($insert, $findId, $groupCode, $group['name'], $groupType, $classId);
        $counts['group']++;

        foreach ($group['accounts'] as $accountCode => $accountName) {
            insertAccount($insert, $findId, $accountCode, $accountName, $groupType, $groupId);
            $counts['account']++;
        }
    }
}

